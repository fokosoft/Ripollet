def rectangulos(filas, letra):
    """Rectángulos (x, y, ancho, alto) que cubren los píxeles de una letra: tramos por fila, fundidos hacia abajo."""
    abiertos, hechos = {}, []
    for y, fila in enumerate(filas + ["." * 16]):
        tramos, x = [], 0
        while x < 16:
            if fila[x] == letra:
                x0 = x
                while x < 16 and fila[x] == letra:
                    x += 1
                tramos.append((x0, x - x0))
            else:
                x += 1
        nuevos = {}
        for t in tramos:
            nuevos[t] = abiertos.pop(t, y)
        hechos += [(x0, y0, w, y - y0) for (x0, w), y0 in abiertos.items()]
        abiertos = nuevos
    return hechos


def symbol(nombre, dibujo):
    filas = [f for f in dibujo.strip("\n").split("\n")]
    assert len(filas) == 16 and all(len(f) == 16 for f in filas), (nombre, [len(f) for f in filas])
    capas = []
    for letra, color in COLORES.items():
        r = rectangulos(filas, letra)
        if r:
            d = "".join(f"M{x} {y}h{w}v{h}h-{w}z" for x, y, w, h in r)
            capas.append(f'<path fill="{color}" d="{d}"/>')
    # primero los rellenos y al final la tinta (que no la tape nada)
    capas.sort(key=lambda c: 'currentColor' in c)
    return f'<symbol id="i-{nombre}" viewBox="0 0 16 16">{"".join(capas)}</symbol>'


